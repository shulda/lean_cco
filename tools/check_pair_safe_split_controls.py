#!/usr/bin/env python3
"""Bounded actual RAW/STRONG and safe-character diagnostics, not Lean proofs.

The finite block/bit/clone windows only supply witnesses for bounded tests;
none is claimed to have unbounded SAP, CCO or infinite gate classes.
"""
from collections import Counter,defaultdict
from itertools import product,combinations
import json,signal,time
START=time.monotonic();C=Counter();I=-1;CL=0;OD=1;FAR=2

def demand(p,msg):
    if not p:raise AssertionError(msg)

def colour(x,y):
    if x==y:return I
    if x[0]!=y[0]:return FAR
    return x[1]^y[1]

def intersection(family,top):
    out=set(top)
    for s in family:out &= set(s)
    return out

def tables():
    pts=tuple(product(range(3),range(2),range(3)));raw=defaultdict(set);strong=defaultdict(set)
    for x,y,z in product(pts,repeat=3):
        a,b,c=colour(x,y),colour(y,z),colour(x,z);raw[a,b].add(c)
        if len({x,y,z})==3:strong[a,b].add(c)
    demand(raw[OD,OD]=={I,CL},'RAW odd square is whole K')
    demand(strong[OD,OD]=={CL},'STRONG odd square is K diversity')
    demand(raw[CL,CL]=={I,CL} and strong[CL,CL]=={CL},'clone square needs third clone')
    demand(raw[FAR,FAR]=={I,CL,OD,FAR},'RAW far square includes Id')
    demand(strong[FAR,FAR]=={CL,OD,FAR},'STRONG far square is diversity top')
    C['actual_triples']=len(pts)**3;C['raw_atom_products']=len(raw);C['strong_atom_products']=len(strong)
    return pts,raw,strong

def mul(A,B,table):return set().union(*(table[a,b] for a in A for b in B))
def mask(e,h,raw=False):return {CL,FAR}|({I} if raw else set()) if e==h else {OD,FAR}
def liftmul(A,B,table,e,m,h,raw=False):return mul(A,B,table)&mask(e,h,raw)

def algebra_controls(raw,strong):
    for rawflag,tab,top,profiles,gates in [
        (False,strong,{CL,OD,FAR},[{CL},{OD},{FAR},{CL,OD,FAR}],[{CL},{CL,OD,FAR}]),
        (True,raw,{I,CL,OD,FAR},[{I},{CL},{I,CL},{OD},{FAR},{I,CL,OD,FAR}],[{I},{I,CL},{I,CL,OD,FAR}])]:
        for flags in product((False,True),repeat=len(profiles)):
            fam=[p for p,take in zip(profiles,flags) if take]
            D=intersection(fam,top)
            if not D:continue
            for Ka,Kb in product(gates,repeat=2):
                lhs=intersection([mul(mul(Ka,p,tab),Kb,tab) for p in fam],top)
                rhs=mul(mul(Ka,D,tab),Kb,tab)
                demand(lhs==rhs,'nonempty exact saturation convention')
                C['raw_saturation_cases' if rawflag else 'strong_saturation_cases']+=1
        for length in range(1,5):
            for word in product((CL,OD,FAR),repeat=length):
                old={word[0]}
                for b in word[1:]:old=mul(old,{b},tab)
                for bits in product((0,1),repeat=length+1):
                    if any(a not in mask(bits[k],bits[k+1],rawflag) for k,a in enumerate(word)):continue
                    L={word[0]}
                    for k,b in enumerate(word[1:],1):L=liftmul(L,{b},tab,bits[0],bits[k],bits[k+1],rawflag)
                    demand(L==old&mask(bits[0],bits[-1],rawflag),'actual two-bit word normal form')
                    demand(bool(L),'legal lifted word nonempty')
                    C['raw_marked_words' if rawflag else 'strong_marked_words']+=1
    for bits in product((0,1),repeat=4):
        e,j,k,h=bits
        for a,b,c in product((CL,OD,FAR),repeat=3):
            if a not in mask(e,j) or b not in mask(j,k) or c not in mask(k,h):continue
            left=liftmul(liftmul({a},{b},strong,e,j,k),{c},strong,e,k,h)
            right=liftmul({a},liftmul({b},{c},strong,j,k,h),strong,e,j,h)
            demand(left==right,'actual lifted STRONG associativity')
            C['lifted_associativity_cases']+=1
    for e,h in product((0,1),repeat=2):
        ps={frozenset(p&mask(e,h)) for p in [{CL},{OD},{FAR},{CL,OD,FAR}] if p&mask(e,h)}
        for flags in product((False,True),repeat=len(ps)):
            fam=[set(p) for p,take in zip(sorted(ps,key=lambda x:tuple(sorted(x))),flags) if take]
            if all(a&b for a,b in combinations(fam,2)):
                demand(bool(intersection(fam,mask(e,h))),'lifted profile Helly')
                C['lifted_Helly_families']+=1
    # Actual full meet can contain Id; the phase-one+Id menu is not an
    # exact domain of this model. Never infer STRONG EPP by deletion alone.
    raw_exact=[{I},{CL},{I,CL},{OD},{FAR},{I,CL,OD,FAR}]
    generated={frozenset({I}),frozenset({CL}),frozenset({OD}),frozenset({FAR})}
    while True:
        nxt=set(generated)
        for A,B in product(generated,repeat=2):
            nxt.add(frozenset(mul(A,B,raw)))
            if A&B:nxt.add(frozenset(A&B))
        if nxt==generated:break
        generated=nxt
    demand(generated=={frozenset(p) for p in raw_exact},'actual exact closure generated by products and nonempty meets')
    demand(frozenset({I,OD}) not in generated,'dangerous extra-identity menu not exact')
    C['generated_raw_exact_domains']=len(generated)
    strong_profiles=[{CL},{OD},{FAR},{CL,OD,FAR}]
    for flags in product((False,True),repeat=len(strong_profiles)):
        fam=[p for p,take in zip(strong_profiles,flags) if take]
        D=intersection(fam,{CL,OD,FAR})
        if not D:continue
        for sheet in [{CL},{OD}]:
            if D<=sheet:demand(any(p<=sheet for p in fam),'actual STRONG EPP')
        C['nonempty_strong_exact_meets']+=1
    for flags in product((False,True),repeat=len(raw_exact)):
        fam=[p for p,take in zip(raw_exact,flags) if take];D=intersection(fam,{I,CL,OD,FAR})
        if not D:continue
        for sheet in [{I,CL},{OD}]:
            if D<=sheet:demand(any(p<=sheet for p in fam),'actual FULL EPP')
        C['nonempty_raw_exact_meets']+=1


def marked_age_controls(pts):
    for x,y,z in product(pts,repeat=3):
        if len({x,y,z})<3:continue
        for a,b in [(x,y),(y,z),(x,z)]:
            demand(colour(a,b) in mask(a[1],b[1]),'actual pair bit legality')
        C['actual_marked_triangles']+=1
    # All current invariant equivalences in this transitive finite window
    # are palette unions. Compare their intersections with the SAP bridge.
    eqs=[]
    for flags in product((False,True),repeat=3):
        menu={I}|{a for a,take in zip((CL,OD,FAR),flags) if take}
        if all(not(colour(x,y) in menu and colour(y,z) in menu) or colour(x,z) in menu
               for x,y,z in product(pts,repeat=3)):
            eqs.append(menu)
    demand({I,CL} in eqs,'gate equivalence exists')
    for E,F in product(eqs,repeat=2):
        if E!={I} and F!={I}:demand(E&F!={I},'nontrivial equivalences not orthogonal')
        C['invariant_equivalence_pairs']+=1
    for width in range(2,7):
        window=tuple(product(range(2),range(2),range(width)))
        for A in [(),(window[0],),(window[0],window[1])]:
            for x in window:
                if x in A:continue
                S=[y for y in window if y not in A and all(colour(y,a)==colour(x,a) for a in A)]
                same=[y for y in S if y[:2]==x[:2]]
                demand(len(same)>=width-len(A),'bounded same-type/gate intersection witnesses')
                demand(all(y[1]==x[1] for y in same),'gate class bits constant')
                C['finite_type_gate_intersections']+=1
    # Explicit marked strong spans: both old legs may have the same owner
    # and must be separated by fresh clone indices, preserving bits.
    small=tuple(product(range(2),range(2),range(2)))
    subsets=[s for k in range(1,4) for s in combinations(small,k)]
    for B in subsets:
        for A in [(),(B[0],)]:
            for T in subsets:
                if not set(A)<=set(T):continue
                host={('A',a):a for a in A};used=defaultdict(int)
                for side,leg in [('B',B),('C',T)]:
                    for x in leg:
                        if x in A:continue
                        key=x[:2];used[key]+=1;host[side,x]=(x[0],x[1],used[key]+2)
                images=[]
                for side,leg in [('B',B),('C',T)]:
                    im={x:host['A',x] if x in A else host[side,x] for x in leg}
                    demand(all(colour(x,y)==colour(im[x],im[y]) for x,y in combinations(leg,2)),'marked leg induced')
                    demand(all(x[1]==im[x][1] for x in leg),'marked leg bits')
                    images.append(set(im.values()))
                demand(images[0]&images[1]==set(A),'strong marked intersection')
                C['bounded_marked_strong_spans']+=1
    for parents in product(range(1,5),repeat=3):
        for flags in product((False,True),repeat=3):
            if not any(flags):continue
            old=sum(3**k for k in parents)
            new=sum(2*3**(k-1) if take else 3**k for k,take in zip(parents,flags))
            demand(new<old,'integer rank decrease');C['rank_decreases']+=1


def generic_sector_boundary():
    # A homogeneous pure unary structure with exactly three P points has
    # every 3-vertex typed triangle but cannot strongly amalgamate two
    # one-point P extensions over a 2-P base. It is not the FULL table age.
    host=tuple((bit,index) for bit in (0,1) for index in range(3))
    for bits in product((0,1),repeat=3):
        witnesses=[xs for xs in product(host,repeat=3)
                   if len(set(xs))==3 and tuple(x[0] for x in xs)==bits]
        demand(bool(witnesses),'generic sector total three-point forks')
        C['generic_three_P_typed_triangles']+=1
    P=[x for x in host if x[0]==1]
    four=[xs for xs in product(P,repeat=4) if len(set(xs))==4]
    demand(not four,'generic sector omits locally legal four-P object')
    # Ordinary AP may identify the two new P images; strong AP cannot.
    ordinary=(P[0],P[1],P[2],P[2])
    demand(ordinary[2]==ordinary[3] and len(set(ordinary))==3,'ordinary AP collision witness')
    C['generic_sector_not_FULL_SAP_boundary']+=1


def main():
    pts,raw,strong=tables();algebra_controls(raw,strong);marked_age_controls(pts);generic_sector_boundary()
    print(json.dumps(dict(status='PASS',seconds=round(time.monotonic()-START,3),counts=dict(sorted(C.items())),
       witnesses=dict(RAW_odd_square=['Id','clone'],STRONG_odd_square=['clone'],
                      dangerous_Id_plus_phase_one_not_exact=True,
                      arbitrary_seed_marking_homogeneity_not_assumed=True),
       limits='Bounded actual clone/phase witnesses only; no finite window is asserted to satisfy unbounded SAP/CCO or infinite type-fibre intersections. Generic sector sufficiency, general exact geometry, external binding or Lean proofs are not certified.'),sort_keys=True))
if __name__=='__main__':
    signal.alarm(30);main()
